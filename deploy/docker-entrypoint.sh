#!/bin/sh
# Container entrypoint: writes a production config.toml and the first API keys
# into the data volume on first start, then runs pkc.
set -eu

STATE=/var/lib/pidchecker
CONF="$STATE/config.toml"
PKC=/opt/pidchecker/pkc
PORT="${PORT:-8675}"

case "$(printf '%s' "${PUBLIC_CHECK:-false}" | tr 'A-Z' 'a-z')" in 1|true|yes|on) PUBLIC_CHECK=true ;; *) PUBLIC_CHECK=false ;; esac
case "$(printf '%s' "${ONLINE_CHECK:-true}" | tr 'A-Z' 'a-z')" in 0|false|no|off) ONLINE_CHECK=false ;; *) ONLINE_CHECK=true ;; esac
case "$(printf '%s' "${TRUST_PROXY_HEADERS:-false}" | tr 'A-Z' 'a-z')" in 1|true|yes|on) TRUST_PROXY_HEADERS=true ;; *) TRUST_PROXY_HEADERS=false ;; esac

if [ ! -w "$STATE" ]; then
    echo "error: $STATE is not writable by uid $(id -u); fix the volume ownership (chown 10001:10001)" >&2
    exit 1
fi

if [ ! -s "$CONF" ]; then
    umask 077
    cat > "$CONF" <<CONFIG
# PID Checker configuration (generated by the container entrypoint on first start).

[server]
host = "0.0.0.0"
port = $PORT
autostart = false
cors = false
max_body_kb = 1024

[rate_limit]
enabled = true
requests_per_minute = 120
burst = 30
trust_proxy_headers = $TRUST_PROXY_HEADERS

[checker]
data_dir = "/opt/pidchecker/data"
blocklist_db = "blocked.redb"
max_batch_size = 500
max_blocklist_batch = 10000
online_check = $ONLINE_CHECK
online_key_types = ["MAK"]
online_timeout_secs = 15
online_chunk_size = 25
online_concurrency = 4
record_blocked = true
record_revoked = true
cache_enabled = true
cache_ttl_secs = 3600
cache_max_entries = 100000
pidgenx_enabled = false
pidgenx_path = "pidgenx.dll"
pidgenx_instances = 0

[api]
require_auth = true
public_check = $PUBLIC_CHECK
keys_file = "api_keys.json"

[catalog]
auto_sync = false
url = "https://raw.githubusercontent.com/ja7ad/PIDChecker/main/data"
interval_hours = 24
CONFIG
    echo "pidchecker: wrote $CONF"
fi

create_key() {
    name="$1"; role="$2"; file="$STATE/$3"
    [ -s "$file" ] && return 0
    token="$("$PKC" -c "$CONF" --log-level warn apikey create --name "$name" --role "$role" | sed -n 's/^Token (shown once): //p')"
    if [ -z "$token" ]; then
        echo "error: could not create the $role API key" >&2
        exit 1
    fi
    (umask 077 && printf '%s\n' "$token" > "$file")
    echo "pidchecker: created $role API key ($name), saved to $file:"
    echo "    $token"
}

if [ "${1:-serve}" = "serve" ]; then
    create_key admin admin admin.key
    create_key browser user browser.key
    shift $(( $# > 0 ? 1 : 0 ))
    exec "$PKC" -c "$CONF" --log-level "${RUST_LOG:-info}" serve "$@"
fi

exec "$PKC" -c "$CONF" "$@"
